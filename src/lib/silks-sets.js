/* ==========================================================================
   The sets of colours this yard's owners carry.

   A set is a thing in its own right, not a property of a horse: colours are
   registered to an owner, several owners can carry the same registered set
   through a partnership, and every horse an owner has runs in them. So the set
   is held once, here, and a horse points at it through its owner.

   Three horses in the string carry the Medallion/Weston claret and navy under
   three different partnership names, and two carry the Reeves green diamond
   under two — which is exactly why this is a list and not a field.

   Each set is a spec for SilksArt. Where a yard holds the real artwork instead,
   drop the PNG into public/silks and name the file after the id: the artwork
   wins over the drawing.
   ========================================================================== */

